#!/usr/bin/env python3
"""Generate crack_tables.h for the CRACK engine.

All values are integers, because the device and the host must compute the same bits.  The macro tables are
piecewise linear over the five knob breakpoints 0 / 32 / 64 / 96 / 127 (the knob is read as an 8.8 word, so the
fractional part is used too).  Frequencies, times and the like are stored as log2 in Q8 and converted with the
pow2 table; levels are Q15, ratios and tilt Q12, semitones and milliseconds Q8.

    python3 engines/crack/gen_crack_tables.py
"""
import math
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE / "crack_tables.h"

Q15 = 32768
Q12 = 4096
Q8 = 256


def q15(x):
    return max(-32768, min(32767, int(round(x * Q15))))


def q12(x):
    return max(-32768, min(32767, int(round(x * Q12))))


def q8(x):
    return max(-32768, min(32767, int(round(x * Q8))))


def lq8(x):
    """log2(x) in Q8."""
    return max(-32768, min(32767, int(round(math.log2(x) * Q8))))


# ---- the macro tables: five columns, 0 / 32 / 64 / 96 / 127 ----------------------------------------------------
MACROS = [
    # name, values, converter
    ("BODY_LVL",     [0.70, 1.00, 0.90, 0.75, 0.30], q15),
    ("WIRE_LVL",     [0.00, 0.55, 0.80, 0.70, 0.40], q15),
    ("WIRE_CUT",     [1200, 2200, 4500, 5500, 2500], lq8),
    ("WIRE_Q",       [0.70, 0.80, 0.90, 1.10, 1.60], q12),
    ("HP_MIX",       [0.20, 0.40, 0.65, 0.70, 0.40], q15),
    ("RATTLE",       [0.00, 0.35, 0.60, 0.50, 0.20], q15),
    ("WIRE_DECAY",   [0.60, 0.90, 1.00, 1.10, 1.30], q12),
    ("CLAP_AMT",     [0.00, 0.00, 0.25, 0.70, 1.00], q15),
    ("CLAP_BURSTS",  [0, 0, 1, 3, 4], int),
    ("CLAP_SPACE",   [9, 9, 9, 10, 11], q8),
    ("AIR_AMT",      [0.00, 0.25, 0.50, 0.70, 0.80], q15),
    ("WIRE_DELAY",   [0.0, 2.5, 1.5, 0.5, 0.0], q8),
    # modes store 12*log2(ratio) in Q8 semitones, so the pitch increment can add it directly
    ("MODE2_SEMI",   [2.000, 1.830, 1.594, 1.594, 2.756], lambda r: q8(12 * math.log2(r))),
    ("MODE3_SEMI",   [3.000, 2.500, 2.136, 2.917, 5.404], lambda r: q8(12 * math.log2(r))),
    ("MODE1_LVL",    [0.70, 1.00, 1.00, 0.80, 0.70], q15),
    ("MODE2_LVL",    [0.056, 0.60, 0.55, 0.60, 0.80], q15),
    ("MODE3_LVL",    [0.00, 0.15, 0.35, 0.60, 0.70], q15),
    ("TENSION_ST",   [13.3, 7, 4, 2, 1], q8),
    ("TENSION_T",    [45, 25, 18, 10, 5], lq8),
    ("PM_INDEX",     [0.00, 0.00, 0.15, 0.40, 1.20], q8),
    ("RING_RATIO",   [2.000, 2.000, 2.296, 2.917, 3.600], q12),
    ("RING_LVL",     [0.00, 0.05, 0.18, 0.35, 0.50], q15),
    ("RING_FB",      [0.00, 0.40, 0.60, 0.75, 0.88], q15),
    ("RING_DAMP",    [0.50, 0.25, 0.50, 0.80, 0.80], q15),
    ("BODY_DECAY",   [1.12, 1.20, 1.00, 0.80, 1.40], q12),
    ("ATTACK_MS",    [6.0, 1.0, 0.0, 0.0, 0.0], q8),
    ("CLICK_LVL",    [0.00, 0.30, 0.70, 1.00, 0.80], q15),
    ("CLICK_DECAY",  [1.0, 1.5, 2.5, 4.0, 6.0], q8),
    ("CLICK_HP",     [2000, 3000, 5000, 3000, 1000], lq8),
    ("SPIKE_ST",     [0, 5, 12, 24, 48], q8),
    ("SPIKE_T",      [3, 3, 4, 8, 25], lq8),
    ("TRANSIENT_DB", [-3, 2, 4, 7, 5], q8),
    ("TRANSIENT_T",  [6, 4, 5, 6, 8], lq8),
    ("DRIVE",        [1.0, 1.6, 2.4, 4.0, 6.0], q8),
    ("CLIP_HARD",    [0.00, 0.00, 0.20, 0.80, 1.00], q15),
    ("COMP_K",       [0.0, 0.5, 1.2, 2.0, 2.0], q12),
    ("TILT",         [0.0, -0.5, 0.6, 0.9, 0.0], q12),
    ("BODY_FAT",     [1.0, 1.1, 1.0, 1.4, 1.2], q15),
    ("WAVEFOLD",     [0.0, 0.0, 0.0, 0.0, 0.6], q15),
    ("MAKEUP",       [1.585, 1.450, 1.000, 0.680, 1.000], q12),
]

# DECAY: body and wire T60 in ms at DECAY 0 / 20 / 40 / 64 / 90 / 100, then held for 101..127.
DECAY_BODY = [25, 80, 210, 350, 900, 1400]
DECAY_WIRE = [20, 110, 310, 500, 1200, 2000]


def main():
    lines = [
        "/* Generated by gen_crack_tables.py -- do not edit by hand. */",
        "#ifndef CRACK_TABLES_H",
        "#define CRACK_TABLES_H",
        "",
        "#include <stdint.h>",
        "",
        "/* 2^(k/12), Q24: the phase increment helper (same table as refmachine.c). */",
        "static const uint32_t CR_SEMI[13] = {",
    ]
    semi = [int(round(2 ** (k / 12) * (1 << 24))) for k in range(13)]
    lines.append("\t" + ", ".join(f"{v}u" for v in semi) + ",")
    lines += [
        "};",
        "",
        "/* 2^(i/32), Q15, for the log-domain macro interpolation. */",
        "static const int32_t CR_POW2[33] = {",
    ]
    pow2 = [int(round(2 ** (i / 32) * Q15)) for i in range(33)]
    lines.append("\t" + ", ".join(str(v) for v in pow2) + ",")
    lines += [
        "};",
        "",
        "/* tan(pi * f / 24000) * 4096, f = 0..10000 Hz in 100 Hz steps. */",
        "static const int16_t CR_TAN_G[101] = {",
    ]
    g = [max(-32768, min(32767, int(round(math.tan(math.pi * f / 24000) * Q12)))) for f in range(0, 10001, 100)]
    lines.append("\t" + ", ".join(str(v) for v in g) + ",")
    lines += [
        "};",
        "",
        "/* 1 - exp(-2*pi*f/48000) in Q15, f = 1000..8000 Hz in 100 Hz steps (the click highpass). */",
        "static const int16_t CR_HP_A[71] = {",
    ]
    h = [int(round((1 - math.exp(-2 * math.pi * f / 48000)) * Q15)) for f in range(1000, 8001, 100)]
    lines.append("\t" + ", ".join(str(v) for v in h) + ",")
    lines += ["};", "", "/* Macro tables, five breakpoints each. */", "enum {"]
    for i, (name, _vals, _conv) in enumerate(MACROS):
        lines.append(f"\tCR_M_{name},")
    lines += [
        "\tCR_M_COUNT",
        "};",
        "",
        "static const int16_t CR_MACRO[CR_M_COUNT][5] = {",
    ]
    for name, vals, conv in MACROS:
        v = [conv(x) for x in vals]
        lines.append("\t/* " + name + " */ {" + ", ".join(str(x) for x in v) + "},")
    lines += [
        "};",
        "",
        "/* DECAY -> T60 (log2 ms Q8) at 0 / 20 / 40 / 64 / 90 / 100; 101..127 use the 100 value. */",
        "static const int16_t CR_DECAY_BODY[6] = {" + ", ".join(str(lq8(x)) for x in DECAY_BODY) + "};",
        "static const int16_t CR_DECAY_WIRE[6] = {" + ", ".join(str(lq8(x)) for x in DECAY_WIRE) + "};",
        "/* DECAY breakpoints in the knob's 8.8 domain (0, 20, 40, 64, 90, 100, 127). */",
        "static const uint16_t CR_DECAY_BP[7] = {0, 5120, 10240, 16384, 23040, 25600, 32512};",
        "",
        "#endif",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.relative_to(HERE.parent.parent)} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
