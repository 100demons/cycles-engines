#!/usr/bin/env python3
"""Generate sheen_tables.h (all SHEEN tables together are under 2 KB).

    python3 engines/sheen/gen_sheen_tables.py

Every value is an integer so the Mac and the device compute the same bits.  Macro tables are piecewise linear over
the five knob breakpoints 0 / 32 / 64 / 96 / 127 in the knob's 0..32766 domain.  Frequencies and times are stored as
log2 Q8 and expanded with the pow2 table; levels and shares are Q15, ratios and tilt Q12, semitones and cents Q8.
"""
import math
import pathlib

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE / "sheen_tables.h"

Q15 = 32768
Q12 = 4096
Q8 = 256


def q15(x):
    return max(-32768, min(32767, int(round(x * Q15))))


def q12(x):
    return max(-32768, min(32767, int(round(x * Q12))))


def q8(x):
    return max(-32768, min(32767, int(round(x * Q8))))


def lq8(x):
    return max(-32768, min(32767, int(round(math.log2(max(x, 1e-6)) * Q8))))


# ---- the macro tables ------------------------------------------------------------------------------------------
MACROS = [
    # COLOR = Metal
    ("METAL",        [0, 0.3, 0.75, 0.8, 1.0], q15),
    ("RING",         [0, 0.6, 0.5, 0.1, 0.0], q15),
    ("OSC14",        [1.0, 1.0, 1.0, 1.0, 0.0], q15),
    ("CUT",          [1.1, 1.05, 1.0, 0.9, 0.35], lq8),
    ("Q",            [0.7, 0.8, 1.0, 1.3, 3.5], q12),
    ("BODY_SHARE",   [0.35, 0.4, 0.5, 0.6, 0.9], q15),
    ("AIR",          [1.0, 0.95, 0.85, 0.6, 0.15], q15),
    ("CHIK",         [0.45, 0.5, 0.55, 0.45, 0.15], q15),
    ("SEND",         [0.0, 0.0, 0.08, 0.15, 0.3], q15),
    # SHAPE = Size
    ("SIZE_SEMI",    [1.8, 1.35, 1.0, 0.75, 0.5], lambda x: q8(12 * math.log2(x))),
    ("SIZE_CUT",     [1.3, 1.12, 1.0, 0.85, 0.6], lq8),
    ("CHIK_HZ",      [4600, 3900, 3200, 2600, 1700], lq8),
    ("SIZE_DECAY",   [0.55, 0.8, 1.0, 1.8, 3.5], q12),
    ("BLOOM",        [0.0, 0.0, 0.1, 0.45, 0.75], q15),
    ("SPREAD",       [0, 3, 8, 16, 28], lambda x: q8(x / 100.0)),
    ("DARKEN",       [0.0, 0.1, 0.38, 0.5, 0.8], q8),
    ("SHIM_LVL",     [0.0, 0.04, 0.08, 0.25, 0.45], q15),
    ("SHIM_FB",      [0.0, 0.3, 0.5, 0.75, 0.9], q15),
    ("SHIM_RATIO",   [6.0, 6.0, 4.7, 3.9, 2.6], q12),
    ("SHIM_DAMP",    [0.85, 0.85, 0.6, 0.55, 0.35], q15),
    # SWEEP = Tick
    ("ATTACK",       [8.0, 2.0, 0.3, 0.02, 0.02], lq8),
    ("TICK_LVL",     [0.0, 0.4, 0.75, 1.0, 0.8], q15),
    ("TICK_DECAY",   [0.4, 0.7, 1.2, 2.0, 4.0], lq8),
    ("TICK_HP",      [6000, 5000, 4000, 2500, 1000], lq8),
    ("CHIK_DECAY",   [1.6, 1.2, 1.0, 0.8, 0.6], q12),
    ("CHIRP_SEMI",   [0, 0, 2, 12, 36], q8),
    ("CHIRP_MS",     [0.02, 0.02, 2, 5, 20], lq8),
    ("SPIKE_OCT",    [0.0, 0.2, 0.4, 0.9, 2.0], q8),
    ("SPIKE_MS",     [0.02, 4, 6, 8, 30], lq8),
    # CONTOUR = Heat
    ("DRIVE",        [1.0, 1.3, 1.8, 6.0, 5.0], q8),
    ("HARD",         [0.0, 0.0, 0.15, 1.0, 1.0], q15),
    ("GLUE",         [0.0, 0.3, 0.8, 0.0, 1.5], q12),
    ("TILT",         [0.0, 0.3, 0.6, 0.4, -0.3], q12),
    ("AIR_MULT",     [0.85, 0.95, 1.0, 0.9, 0.2], q15),
    ("MAKEUP",       [1.35, 1.0, 1.0, 0.31, 1.0], q12),
]

# DECAY T60 in ms at DECAY 0 / 20 / 40 / 64 / 90 / 100.  101..127 are the reverse swell (not these values).
DECAYS = [
    ("CLOSED_BODY",  [6, 18, 35, 80, 220, 400]),
    ("CLOSED_SIZZ",  [10, 30, 60, 140, 380, 650]),
    ("OPEN_BODY",    [90, 200, 350, 700, 1600, 2500]),
    ("OPEN_SIZZ",    [150, 380, 700, 1300, 3000, 4500]),
    ("CHIK",         [4, 8, 14, 20, 30, 40]),
]


def main():
    lines = [
        "/* Generated by gen_sheen_tables.py -- do not edit by hand. */",
        "#ifndef SHEEN_TABLES_H",
        "#define SHEEN_TABLES_H",
        "",
        "#include <stdint.h>",
        "",
        "/* 2^(k/12), Q24 (the same semitone table as refmachine.c). */",
        "static const uint32_t SH_SEMI[13] = {",
    ]
    semi = [int(round(2 ** (k / 12) * (1 << 24))) for k in range(13)]
    lines.append("\t" + ", ".join(f"{v}u" for v in semi) + ",")
    lines += [
        "};",
        "",
        "/* 2^(i/32), Q15, for log-domain interpolation. */",
        "static const int32_t SH_POW2[33] = {",
    ]
    pow2 = [int(round(2 ** (i / 32) * Q15)) for i in range(33)]
    lines.append("\t" + ", ".join(str(v) for v in pow2) + ",")
    lines += [
        "};",
        "",
        "/* tan(pi * f / 24000) * 4096, 0..10500 Hz in 100 Hz steps (the TPT SVF). */",
        "static const int16_t SH_TAN_G[106] = {",
    ]
    g = [max(-32768, min(32767, int(round(math.tan(math.pi * f / 24000) * Q12))))
         for f in range(0, 10501, 100)]
    lines.append("\t" + ", ".join(str(v) for v in g) + ",")
    lines += [
        "};",
        "",
        "/* 1 - exp(-2*pi*f/48000) in Q15, 0..16000 Hz in 100 Hz steps (one-pole highpasses; the 24 kHz",
        "   pre-highpass at f uses this table at 2*f). */",
        "static const int16_t SH_HP_A[161] = {",
    ]
    h = [int(round((1 - math.exp(-2 * math.pi * f / 48000)) * Q15)) for f in range(0, 16001, 100)]
    lines.append("\t" + ", ".join(str(v) for v in h) + ",")
    lines += [
        "};",
        "",
        "/* 2*r*cos(2*pi*f/24000) in Q14, f = 1500..5000 Hz in 50 Hz steps (the chik resonator, r = 0.83). */",
        "static const int16_t SH_CHIK_A[71] = {",
    ]
    r = 0.83
    ca = [int(round(2 * r * math.cos(2 * math.pi * f / 24000) * 16384))
          for f in range(1500, 5001, 50)]
    lines.append("\t" + ", ".join(str(v) for v in ca) + ",")
    lines += [
        "};",
        "",
        "/* TR-808 cymbal oscillator ratios, 12*log2(ratio) in Q8 semitones. */",
        "static const int16_t SH_OSC_SEMI[6] = {" +
        ", ".join(str(q8(12 * math.log2(x))) for x in (1.0, 1.4827, 1.8003, 2.5460, 2.6303, 3.8967)) + "};",
        "/* Wash detune direction, Q8 of the spread. */",
        "static const int16_t SH_OSC_DET[6] = {256, -256, 154, -154, 77, -77};",
        "",
    ]
    # the metal note offset: note 60 is 205.3 Hz (MIDI 55.79)
    off = 12 * math.log2(205.3 / 261.6255653005986)
    lines += [
        f"/* note 60 -> 205.3 Hz: {off:.6f} semitones, Q16. */",
        f"#define SH_METAL_OFF ({int(round(off * 65536))})",
        f"/* log2 Hz Q8 of the home metal base, the closed and the open voice cutoff. */",
        f"#define SH_HOME_HZ_LOG ({lq8(205.3)})",
        f"#define SH_CUT_CLOSED_LOG ({lq8(7800)})",
        f"#define SH_CUT_OPEN_LOG ({lq8(7000)})",
        "/* 16 kHz at 48 kHz, the mute threshold for a metal oscillator. */",
        f"#define SH_MUTE_INC ({int(round(16000 / 48000 * (1 << 32)))}u)",
        "",
        "/* Macro tables: five breakpoints each (0 / 32 / 64 / 96 / 127). */",
        "enum {",
    ]
    for i, (name, _v, _c) in enumerate(MACROS):
        lines.append(f"\tSH_M_{name},")
    lines += [
        "\tSH_M_COUNT",
        "};",
        "",
        "static const int16_t SH_MACRO[SH_M_COUNT][5] = {",
    ]
    for name, vals, conv in MACROS:
        v = [conv(x) for x in vals]
        lines.append("\t/* " + name + " */ {" + ", ".join(str(x) for x in v) + "},")
    lines += [
        "};",
        "",
        "/* DECAY -> T60 (log2 ms Q8) at 0 / 20 / 40 / 64 / 90 / 100. */",
    ]
    for name, vals in DECAYS:
        lines.append("static const int16_t SH_DECAY_" + name + "[6] = {" +
                     ", ".join(str(lq8(x)) for x in vals) + "};")
    lines += [
        "/* DECAY breakpoints in the knob's 8.8 domain. */",
        "static const uint16_t SH_DECAY_BP[6] = {0, 5120, 10240, 16384, 23040, 25600};",
        "",
        "#endif",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.relative_to(HERE.parent.parent)} ({OUT.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
