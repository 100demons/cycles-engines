#!/usr/bin/env python3
"""Generates docs/flasher/engines.js from engines/*/ for the web flasher.

The web flasher builds the .syx in the browser; it needs the engines. Rather than fetching paths (fragile under
GitHub Pages, and it does not work on file://), they are embedded in a small generated .js. Single source of truth:
this script copies, it invents nothing. An engine package is offered on the page when it has a card.json; the
committed object is laid out once (core/compose.web_package) and the registrar's frame (core/registrar/frame.json)
is embedded, so docs/flasher/composer.js composes the ticked engines into one tweak.

    python3 tools/make_catalog.py            # (re)generate docs/flasher/engines.js
    python3 tools/make_catalog.py --check    # verify it is up to date (CI)
"""
import argparse
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent
sys.path.insert(0, str(ROOT / "core"))

import compose                            # noqa: E402

ENGINES = ROOT / "engines"
OUT = ROOT / "docs" / "flasher" / "engines.js"
DEVICE = ROOT / "core" / "os113_dev.json"
FRAME = ROOT / "core" / "registrar" / "frame.json"


def engine_cards():
    """The engines offered on the page, in slot order: every package with a card.json, by its manifest order."""
    cards = []
    for d in sorted(p for p in ENGINES.iterdir() if p.is_dir()):
        mf = d / "manifest.json"
        cf = d / "card.json"
        if not mf.is_file() or not cf.is_file():
            continue
        m = json.loads(mf.read_text(encoding="utf-8"))
        card = json.loads(cf.read_text(encoding="utf-8"))
        cards.append((m["order"], m["id"], card, m.get("version"), m.get("name"), m.get("cost")))
    cards.sort()
    return [{"id": mid, "card": card, "version": version, "name": name, "cost": cost}
            for _order, mid, card, version, name, cost in cards]


def render():
    device = json.loads(DEVICE.read_text(encoding="utf-8"))
    registrar = json.loads(FRAME.read_text(encoding="utf-8"))
    engines = engine_cards()
    packages = {e["id"]: compose.web_package(e["id"]) for e in engines}
    payload = {
        "device": {k: device[k] for k in ("device", "os", "section_sha256", "stock_syx_sha256") if k in device},
        "registrar": registrar,
        "engines": engines,
        "packages": packages,
    }
    body = json.dumps(payload, ensure_ascii=False, indent=1)
    text = (
        "/* Generated by tools/make_catalog.py from the engine packages.\n"
        " * DO NOT edit by hand: rerun the script after changing an engine. */\n"
        "window.MC_ENGINES = " + body + ";\n"
    )
    return text


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="verify without writing")
    args = ap.parse_args()
    text = render()
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            sys.exit("!! docs/flasher/engines.js is not up to date: rerun tools/make_catalog.py")
        print("docs/flasher/engines.js is up to date")
        return
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(text)} o)")


if __name__ == "__main__":
    main()
