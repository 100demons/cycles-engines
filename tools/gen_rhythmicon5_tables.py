#!/usr/bin/env python3
"""Generate engines/rhythmicon5/r5_tables.h and r5_cloud_tables.h.

The Rhythmicon tables come from Feral's tiny2_tables.h (T_SIN, T_INC, T_RATI_NORM), the same source as FIFTH.
T_RATE is FIFTH's sweep curve; T_R5_RING is the new SHAPE -> T60 curve (325 ms down to 20 ms, log spaced).

The cloud tables are copied verbatim from HALO New's generated halo_tables.h (only the tables the cloud uses).
No HALO file is modified.

    python3 tools/gen_rhythmicon5_tables.py [--halo /path/to/halo_tables.h]
"""
import argparse
import hashlib
import pathlib
import re

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent
SRC = ROOT / "engines" / "feral9" / "tiny2_tables.h"
OUT = ROOT / "engines" / "rhythmicon5"
HALO_DEFAULT = ROOT.parent / "model27" / "tools" / "machines" / "halo" / "halo_tables.h"

CLOUD_DEFINES = [
    "HALO_GRAINS", "HALO_CLOUD_DIV", "HALO_DIFF", "HALO_SUBC", "HALO_CD_SHIFT", "HALO_DIFF_TOTAL",
    "HALO_BUF_LEN", "HALO_POSINIT", "HALO_DIFF_K", "HALO_A_LP", "HALO_A_HP", "HALO_A_C", "HALO_K427",
    "HALO_DL0", "HALO_DL1", "HALO_DL2", "HALO_DL3",
]
CLOUD_TABLES = [
    "TIM_POS", "TIM_SIZE", "TIM_EINC", "TIM_SIZE_S", "CLD_DENS", "CLD_DENS16", "CLD_WET", "CLD_DRY",
    "CLD_FB", "CLD_DIFF", "CLD_JIT", "CLD_DET", "CLD_SHIM", "RSQRT_OV", "HANN1K",
]


def array(text, name):
    m = re.search(r"static const (?:s32|u32|s16) %s\[\d+\] = \{(.*?)\};" % name, text, re.S)
    if not m:
        raise SystemExit(f"!! {name} not found")
    return [int(x, 0) for x in re.findall(r"-?(?:0x[0-9a-fA-F]+|\d+)", m.group(1))]


def emit(name, typ, vals, per_line=8):
    lines = [f"static const {typ} {name}[{len(vals)}] = {{"]
    for i in range(0, len(vals), per_line):
        lines.append("\t" + ", ".join(str(v) for v in vals[i:i + per_line]) + ",")
    lines.append("};")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--halo", default=str(HALO_DEFAULT), help="HALO New's halo_tables.h")
    args = ap.parse_args()

    text = SRC.read_text(encoding="utf-8")
    sin = array(text, "T_SIN")
    inc = array(text, "T_INC")
    norm = array(text, "T_RATI_NORM")

    # FIFTH's sweep curve, unchanged: 2^(-10 + 4s/64) then 2^(-6 + 6(s-64)/63), Q16.
    rate = []
    for s in range(129):
        if s <= 64:
            e = -10.0 + 4.0 * s / 64.0
        else:
            e = -6.0 + 6.0 * (s - 64) / 63.0
        rate.append(max(1, min(65536, int(round(65536.0 * 2.0 ** e)))))

    # SHAPE -> T60: 325 ms at 0, 20 ms at 127, log spaced. The PING loop takes 16 internal steps per
    # 32-frame block, i.e. one update every two frames: 24 kHz.
    ring = []
    for s in range(129):
        u = min(s, 127)
        t60 = 0.325 * (0.020 / 0.325) ** (u / 127.0)
        r = 10.0 ** (-3.0 / (t60 * 24000.0))
        ring.append(min(65535, int(round(65536.0 * r))))

    body = "\n\n".join([
        emit("T_SIN", "s32", sin),
        emit("T_INC", "u32", inc),
        emit("T_RATI_NORM", "s32", norm),
        emit("T_RATE", "u32", rate),
        emit("T_R5_RING", "s32", ring),
    ])
    (OUT / "r5_tables.h").write_text(
        "/* Generated by tools/gen_rhythmicon5_tables.py. Do not edit by hand.\n"
        " *\n"
        " * T_SIN, T_INC and T_RATI_NORM: Feral's tiny2_tables.h (MIT, 100demons and Claude).\n"
        " * T_RATE: FIFTH's SWEEP -> ping-rate scale, 2^(-10 + 4s/64) then 2^(-6 + 6(s-64)/63), Q16.\n"
        " * T_R5_RING: SHAPE -> two-pole pole radius per internal step, Q16, T60 325 ms (0) .. 20 ms (127),\n"
        " *             T60 = 325 ms x (20 / 325)^(SHAPE / 127), at the resonator's 24 kHz update rate.\n"
        " */\n\n" + body + "\n",
        encoding="utf-8")

    halo_path = pathlib.Path(args.halo)
    halo_text = halo_path.read_text(encoding="utf-8")
    halo_sha = hashlib.sha256(halo_path.read_bytes()).hexdigest()

    defs = []
    for name in CLOUD_DEFINES:
        m = re.search(r"^#define %s\s+(.+)$" % re.escape(name), halo_text, re.M)
        if not m:
            raise SystemExit(f"!! #define {name} not found in {halo_path}")
        defs.append(f"#define {name} {m.group(1)}")

    arrays = []
    for name in CLOUD_TABLES:
        m = re.search(r"^static const (?:s32|u32|s16) %s\[\d+\] = \{.*?^\};" % re.escape(name),
                      halo_text, re.M | re.S)
        if not m:
            raise SystemExit(f"!! {name} not found in {halo_path}")
        arrays.append(m.group(0))

    (OUT / "r5_cloud_tables.h").write_text(
        "/* Generated by tools/gen_rhythmicon5_tables.py. Do not edit by hand.\n"
        " *\n"
        " * The cloud tables of HALO New, copied verbatim from\n"
        f" * {halo_path}\n"
        f" * SHA-256 {halo_sha}\n"
        " * Only the definitions the granular cloud reads are kept; the values are unchanged.\n"
        " */\n"
        "#ifndef R5_CLOUD_TABLES_H\n#define R5_CLOUD_TABLES_H\n\n"
        + "\n".join(defs) + "\n\n" + "\n\n".join(arrays) + "\n\n#endif\n",
        encoding="utf-8")
    print(f"wrote {OUT / 'r5_tables.h'}")
    print(f"wrote {OUT / 'r5_cloud_tables.h'}")


if __name__ == "__main__":
    main()
