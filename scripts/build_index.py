#!/usr/bin/env python3
"""Rebuild the machine-readable and human-readable engine lists.

Reads  engines/<id>/engine.json  (one "card" per engine)
Writes index.json                (for tools and other developers' flashers)
       ENGINES.md                (a table for humans)
       README.md                 (only the part between the ENGINES:START / ENGINES:END markers)

Usage:
  python3 scripts/build_index.py           rebuild the files
  python3 scripts/build_index.py --check   change nothing; exit 1 if the files are out of date or a card is invalid

Folders whose name starts with "_" (like _template) are ignored.
Needs only Python 3.
"""
import argparse
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
ENGINES_DIR = ROOT / "engines"
REQUIRED = ["id", "name", "version", "status", "author", "license", "summary", "base_os", "files"]
STATUSES = ["experimental", "emulated", "tested"]
START = "<!-- ENGINES:START (generated by scripts/build_index.py, do not edit by hand) -->"
END = "<!-- ENGINES:END -->"


def load_cards():
    cards, errors = [], []
    if not ENGINES_DIR.is_dir():
        return cards, [f"{ENGINES_DIR} does not exist"]
    for folder in sorted(p for p in ENGINES_DIR.iterdir() if p.is_dir() and not p.name.startswith(("_", "."))):
        card_path = folder / "engine.json"
        if not card_path.exists():
            errors.append(f"{folder.name}: missing engine.json")
            continue
        try:
            card = json.loads(card_path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:
            errors.append(f"{folder.name}: engine.json is not valid JSON ({exc})")
            continue
        missing = [k for k in REQUIRED if k not in card]
        if missing:
            errors.append(f"{folder.name}: engine.json is missing {', '.join(missing)}")
            continue
        if card["id"] != folder.name:
            errors.append(f"{folder.name}: id is '{card['id']}' but the folder is '{folder.name}' (they must match)")
        if card["status"] not in STATUSES:
            errors.append(f"{folder.name}: status must be one of {STATUSES}, not '{card['status']}'")
        if not isinstance(card["files"], list) or not card["files"]:
            errors.append(f"{folder.name}: 'files' must be a non-empty list")
        else:
            for rel in card["files"]:
                if not (folder / rel).exists():
                    errors.append(f"{folder.name}: file listed in engine.json does not exist: {rel}")
        for key in ("requires", "conflicts"):
            if key in card and not isinstance(card[key], list):
                errors.append(f"{folder.name}: '{key}' must be a list")
        cards.append((folder.name, card))
    return cards, errors


def make_index(cards):
    engines = []
    for folder, card in cards:
        engines.append({
            "id": card["id"],
            "name": card["name"],
            "version": card["version"],
            "status": card["status"],
            "summary": card["summary"],
            "author": card["author"],
            "license": card["license"],
            "base_os": card["base_os"],
            "path": f"engines/{folder}",
            "files": [f"engines/{folder}/{f}" for f in card["files"]],
            "knobs": card.get("knobs", []),
            "requires": card.get("requires", []),
            "conflicts": card.get("conflicts", []),
            "tested_on_hardware": card.get("tested_on_hardware"),
        })
    return {"index_version": 1, "generated_by": "scripts/build_index.py", "engines": engines}


def make_table(cards):
    lines = ["| Engine | What it does | Status | Version | Folder |",
             "|---|---|---|---|---|"]
    if not cards:
        lines.append("| (none yet) | | | | |")
    for folder, card in cards:
        summary = card["summary"].replace("|", "/")
        lines.append(f"| **{card['name']}** | {summary} | {card['status']} | {card['version']} | "
                     f"[`engines/{folder}`](engines/{folder}) |")
    return "\n".join(lines) + "\n"


def update_readme(text, table):
    block = f"{START}\n{table}{END}"
    if START in text and END in text:
        before = text.split(START)[0]
        after = text.split(END, 1)[1]
        return before + block + after
    return text  # no markers: leave README alone


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="verify only; change nothing")
    args = ap.parse_args()

    cards, errors = load_cards()
    if errors:
        print("Problems found in the engine cards:")
        for e in errors:
            print("  -", e)
        return 1

    index_text = json.dumps(make_index(cards), indent=2, ensure_ascii=False) + "\n"
    table = make_table(cards)
    engines_md = "# Engines\n\nGenerated by `scripts/build_index.py`. Edit each engine's `engine.json`, not this file.\n\n" + table

    readme_path = ROOT / "README.md"
    readme_old = readme_path.read_text(encoding="utf-8") if readme_path.exists() else ""
    readme_new = update_readme(readme_old, table) if readme_old else ""

    targets = [(ROOT / "index.json", index_text), (ROOT / "ENGINES.md", engines_md)]
    if readme_old:
        targets.append((readme_path, readme_new))

    stale = [p.name for p, new in targets if not p.exists() or p.read_text(encoding="utf-8") != new]

    if args.check:
        if stale:
            print("Out of date: " + ", ".join(stale) + ". Run: python3 scripts/build_index.py")
            return 1
        print(f"OK: index.json, ENGINES.md and README table are up to date ({len(cards)} engine(s)).")
        return 0

    for path, new in targets:
        path.write_text(new, encoding="utf-8")
    print(f"Wrote index.json, ENGINES.md and the README table for {len(cards)} engine(s).")
    return 0


if __name__ == "__main__":
    sys.exit(main())
